'use strict';

/**
 * Pull Supabase secrets from AWS SSM and render them into an environment file
 * for the n8n service on the EC2 host.
 *
 * Usage:
 *   node scripts/apply-supabase-secrets.js --output /etc/n8n/env.d/50-supabase.env
 *   node scripts/apply-supabase-secrets.js --print   # prints exports instead
 *
 * The script relies on the AWS CLI for fetching SecureString parameters so the
 * current user must have permission to run `aws ssm get-parameter`.
 */

const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const namespace = process.env.ALEX_AI_PARAMETER_NAMESPACE || '/alex-ai/supabase';
const outputIndex = process.argv.indexOf('--output');
const formatIndex = process.argv.indexOf('--format');
const explicitFormat = formatIndex !== -1 ? process.argv[formatIndex + 1] : undefined;
const shouldPrint = process.argv.includes('--print') || outputIndex === -1;
const format = explicitFormat || (shouldPrint ? 'exports' : 'file');
const outputFile =
  outputIndex === -1 ? null : path.resolve(process.argv[outputIndex + 1] || '');

const PARAMETERS = [
  'supabase-url',
  'supabase-service-role-key',
  'supabase-anon-key',
  'supabase-api-key',
  'openai-api-key',
];

function fetchParameter(name) {
  const parameterName = `${namespace}/${name}`;
  const args = ['ssm', 'get-parameter', '--name', parameterName, '--with-decryption'];
  const result = spawnSync('aws', args, { encoding: 'utf8' });

  if (result.status !== 0) {
    throw new Error(`Failed to read ${parameterName}: ${result.stderr || result.stdout}`);
  }

  const payload = JSON.parse(result.stdout || '{}');
  return payload.Parameter ? payload.Parameter.Value : undefined;
}

function renderExports(values) {
  const lines = [
    '# Supabase credentials synced from AWS SSM',
    '# Generated by scripts/apply-supabase-secrets.js',
  ];

  Object.entries(values).forEach(([key, value]) => {
    if (!value) return;
    lines.push(`export ${key}=${JSON.stringify(value)}`);
  });

  lines.push('');
  return lines.join('\n');
}

function renderPlain(values) {
  return Object.entries(values)
    .filter(([, value]) => value)
    .map(([key, value]) => `${key}=${value}`)
    .join('\n');
}

function main() {
  const envValues = {};

  PARAMETERS.forEach((slug) => {
    const key = slug.toUpperCase().replace(/-/g, '_');
    try {
      const value = fetchParameter(slug);
      if (value) envValues[key] = value;
    } catch (err) {
      if (slug !== 'supabase-api-key') {
        console.error(err.message.trim());
      }
    }
  });

  if (Object.keys(envValues).length === 0) {
    console.error('No parameters retrieved; aborting.');
    process.exit(1);
  }

  if (format === 'json') {
    console.log(JSON.stringify(envValues, null, 2));
    return;
  }

  if (format === 'plain') {
    console.log(renderPlain(envValues));
    return;
  }

  const rendered = renderExports(envValues);

  if (format === 'exports') {
    console.log(rendered);
    return;
  }

  if (!outputFile) {
    console.error('No output path provided. Use --output or --print.');
    process.exit(1);
  }

  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, rendered, { encoding: 'utf8', mode: 0o600 });
  console.log(`Supabase environment file written to ${outputFile}`);
}

main();

